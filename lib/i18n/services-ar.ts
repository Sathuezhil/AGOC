export function localizeService(service: Service, locale: "en" | "ar"): Service {
  if (locale !== "ar") return service;
  const ar = SERVICES_AR[service.slug];
  if (!ar) return service;
  return {
    ...service,
    title: ar.title,
    short: ar.short,
    summary: ar.summary,
    points: ar.points,
  };
}

export function localizeServices(services: Service[], locale: "en" | "ar") {
  return services.map((service) => localizeService(service, locale));
}
